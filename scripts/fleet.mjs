#!/usr/bin/env node
// Fleet tool: one brand file per operator app (fleet/brands/*.json) and one version
// policy (fleet/policy.json). Needs the contracts build: pnpm build:contracts.
//
//   node scripts/fleet.mjs check              validate everything; exits 1 on any problem (CI runs this)
//   node scripts/fleet.mjs generate           write the brand xcconfigs and the backend's copy of the fleet
//   node scripts/fleet.mjs matrix <ring> [slug,slug]   GitHub Actions matrix for a release
//   node scripts/fleet.mjs list               one line per app
import { createRequire } from 'node:module';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const C = require(join(ROOT, 'packages/contracts/dist/index.js'));

const BRANDS_DIR = join(ROOT, 'fleet/brands');
const ASSETS = join(ROOT, 'ios/Resources/Assets.xcassets');
const BACKEND_DATA = join(ROOT, 'backend/src/fleet/fleet.data.ts');
const xcconfigPath = (slug) => join(ROOT, 'ios/Config', `${slug[0].toUpperCase()}${slug.slice(1)}.xcconfig`);

function load() {
  const problems = [];
  const files = readdirSync(BRANDS_DIR).filter((f) => f.endsWith('.json')).sort();
  const brands = [];
  const slugs = [];
  for (const f of files) {
    const r = C.BrandManifest.safeParse(JSON.parse(readFileSync(join(BRANDS_DIR, f), 'utf8')));
    if (!r.success) problems.push(...r.error.issues.map((i) => `${f}: ${i.path.join('.') || '(file)'} ${i.message}`));
    else {
      brands.push(r.data);
      slugs.push(f.replace(/\.json$/, ''));
    }
  }
  const pr = C.FleetPolicy.safeParse(JSON.parse(readFileSync(join(ROOT, 'fleet/policy.json'), 'utf8')));
  if (!pr.success) problems.push(...pr.error.issues.map((i) => `policy.json: ${i.path.join('.')} ${i.message}`));
  const policy = pr.success ? pr.data : null;
  if (policy) problems.push(...C.fleetProblems(brands, policy, slugs));
  return { brands, policy, problems };
}

const backendData = (brands, policy) =>
  [
    '// Generated by scripts/fleet.mjs from fleet/brands and fleet/policy.json. Do not edit by hand.',
    "import type { BrandManifest, FleetPolicy } from '@cinema/contracts';",
    '',
    `export const FLEET_BRANDS: BrandManifest[] = ${JSON.stringify(brands, null, 2)};`,
    '',
    `export const FLEET_POLICY: FleetPolicy = ${JSON.stringify(policy, null, 2)};`,
    '',
  ].join('\n');

const marketingVersion = () => readFileSync(join(ROOT, 'ios/Config/Base.xcconfig'), 'utf8').match(/^MARKETING_VERSION = (.+)$/m)?.[1].trim();

const [cmd, ...args] = process.argv.slice(2);
const { brands, policy, problems } = load();

if (cmd === 'check') {
  for (const b of brands) {
    if (!existsSync(join(ASSETS, `${b.appIcon}.appiconset`)) && !existsSync(join(ROOT, 'ios/Resources', `${b.appIcon}.icon`))) problems.push(`${b.slug}: icon "${b.appIcon}" is not in ios/Resources`);
    const x = xcconfigPath(b.slug);
    if (!existsSync(x) || readFileSync(x, 'utf8') !== C.xcconfigFor(b)) problems.push(`${b.slug}: ${x.replace(ROOT + '/', '')} is out of date; run node scripts/fleet.mjs generate`);
  }
  if (policy) {
    if (!existsSync(BACKEND_DATA) || readFileSync(BACKEND_DATA, 'utf8') !== backendData(brands, policy)) problems.push('backend/src/fleet/fleet.data.ts is out of date; run node scripts/fleet.mjs generate');
    const mv = marketingVersion();
    if (mv && C.compareVersions(policy.ios.latestVersion, mv) > 0) problems.push(`policy latestVersion ${policy.ios.latestVersion} is newer than the app's MARKETING_VERSION ${mv}`);
  }
  if (problems.length) {
    console.error(problems.map((p) => `::error::${p}`).join('\n'));
    process.exit(1);
  }
  console.log(`Fleet OK: ${brands.length} apps, iOS latest ${policy.ios.latestVersion}, minimum ${policy.ios.minimumVersion}.`);
} else if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
} else if (cmd === 'generate') {
  for (const b of brands) writeFileSync(xcconfigPath(b.slug), C.xcconfigFor(b));
  writeFileSync(BACKEND_DATA, backendData(brands, policy));
  console.log(`Wrote ${brands.length} xcconfigs and backend/src/fleet/fleet.data.ts`);
} else if (cmd === 'matrix') {
  const ring = C.Ring.parse(args[0] ?? 'internal');
  const only = args[1] ? args[1].split(',').map((s) => s.trim()).filter(Boolean) : null;
  let picked = C.brandsForRing(brands, ring);
  if (only) {
    const unknown = only.filter((s) => !brands.some((b) => b.slug === s));
    if (unknown.length) throw new Error(`Unknown brand: ${unknown.join(', ')}`);
    picked = picked.filter((b) => only.includes(b.slug));
  }
  console.log(JSON.stringify(picked.map((b) => ({ slug: b.slug, appName: b.appName, secretSuffix: b.secretSuffix }))));
} else if (cmd === 'list') {
  for (const b of brands) console.log(`${b.slug.padEnd(16)} ${b.ring.padEnd(9)} ${b.status.padEnd(7)} ${b.bundleId}  team ${b.appleTeamId}`);
} else {
  console.error('Usage: node scripts/fleet.mjs check | generate | matrix <ring> [slugs] | list');
  process.exit(2);
}
